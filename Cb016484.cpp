/** @brief Hardware timer: 10 ms periodic interrupt. */
static void startTickTimer() {
#if ESP_ARDUINO_VERSION_MAJOR >= 3
  gTimer = timerBegin(1000000);                    // 1 MHz timer clock
  timerAttachInterrupt(gTimer, &onTimerTick);
  timerAlarm(gTimer, TICK_PERIOD_US, true, 0);     // auto-reload
#else
  gTimer = timerBegin(0, 80, true);                // 80 MHz / 80 = 1 MHz
  timerAttachInterrupt(gTimer, &onTimerTick, true);
  timerAlarmWrite(gTimer, TICK_PERIOD_US, true);
  timerAlarmEnable(gTimer);
#endif
}

void setup() {
  Serial.begin(115200);

  pinMode(PIN_LED_BLUE,   OUTPUT);
  pinMode(PIN_LED_YELLOW, OUTPUT);
  pinMode(PIN_LED_RED,    OUTPUT);
  pinMode(PIN_BUTTON,     INPUT_PULLUP);
  pinMode(PIN_LDR,        INPUT);
  pinMode(PIN_POT,        INPUT);
  attachInterrupt(digitalPinToInterrupt(PIN_BUTTON), onButton, FALLING);

  analogReadResolution(12);

  pwmAttach(PIN_SERVO_A,   SERVO_FREQ_HZ, SERVO_RES_BITS, CH_SERVO_A);
  pwmAttach(PIN_SERVO_B,   SERVO_FREQ_HZ, SERVO_RES_BITS, CH_SERVO_B);
  pwmAttach(PIN_LED_WHITE, GROW_FREQ_HZ,  GROW_RES_BITS,  CH_GROW);
  servoWriteDeg(PIN_SERVO_A, CH_SERVO_A, VENT_CLOSED_DEG);
  servoWriteDeg(PIN_SERVO_B, CH_SERVO_B, VENT_CLOSED_DEG);
  pwmWrite(PIN_LED_WHITE, CH_GROW, 0);

  Wire.begin(PIN_I2C_SDA, PIN_I2C_SCL);
  Wire.setClock(400000);                           // faster redraw (~25 ms)
  gOledOk = oled.begin(SSD1306_SWITCHCAPVCC, OLED_ADDR);
  if (gOledOk) {
    oled.clearDisplay();
    oled.setTextColor(SSD1306_WHITE);
    oled.setTextSize(1);
    oled.setCursor(0, 20);
    oled.println("Micro-Climate Nursery");
    oled.println("Starting...");
    oled.display();
  } else {
    Serial.println(F("[OLED] not found at 0x3C - check SDA/SCL wiring"));
  }

  dht.begin();
  startTickTimer();
  printHelp();
  Serial.println(F("[MODE] -> AUTO (power on)"));
}

void loop() {
  static uint32_t tServo = 0, tControl = 0, tDht = 0, tOled = 0, tStatus = 0;

  pollSerial();
  if (gButtonFlag) { gButtonFlag = false; handleButton(); }

  uint32_t now = gTick;
  if (now - tServo   >= TICKS_SERVO)   { tServo = now;   updateServos(); }
  if (now - tDht     >= TICKS_DHT)     { tDht = now;     readDht(); }
  if (now - tControl >= TICKS_CONTROL) {
    tControl = now;
    readAnalogSensors();
    updateMode(now);
    runControl();
    updateIndicators(now);
  }
  if (now - tOled    >= TICKS_OLED)    { tOled = now;    drawOled(now); }
  if (now - tStatus  >= TICKS_STATUS)  { tStatus = now;  printStatusLine(); }
}
