/** @brief Runtime-tunable parameters for the "set" command. */
struct ParamDef { const char *key; float *val; float lo, hi; const char *desc; };
static ParamDef PARAMS[] = {
  { "vent",  &cfg.tVent,          10,   45, "indoor temp where venting starts (C)" },
  { "band",  &cfg.tBand,           1,   20, "rise above vent temp for 100% open (C)" },
  { "crit",  &cfg.tCrit,          20,   50, "critical heat, full vent (C)" },
  { "min",   &cfg.tMinIn,          0,   30, "indoor too cold, never vent (C)" },
  { "frost", &cfg.tFrost,        -10,   15, "outdoor frost limit (C)" },
  { "fcap",  &cfg.frostCapPct,     0,  100, "max vent when frosty (%)" },
  { "hum",   &cfg.humMax,         40,  100, "humidity for air-circulation vent (%)" },
  { "safe",  &cfg.safeVentPct,     0,  100, "FAULT safe vent position (%)" },
  { "lon",   &cfg.lightOnPct,      0,  100, "grow light ON below (%)" },
  { "loff",  &cfg.lightOffPct,     0,  100, "grow light OFF above (%)" },
  { "mto",   &cfg.manualTimeoutS,  0, 7200, "manual auto-resume, 0 = off (s)" },
  { "out",   &cfg.tOutdoor,      -20,   50, "simulated outdoor temperature (C)" },
};
static const size_t N_PARAMS = sizeof(PARAMS) / sizeof(PARAMS[0]);

/** @brief Print the command list and current parameter values. */
static void printHelp() {
  Serial.println(F("\n=== Nursery controller commands ==="));
  Serial.println(F(" help | status | manual | auto | ack"));
  Serial.println(F(" set <param> <value>"));
  Serial.println(F(" inject dht | inject ldr | inject off   (fault test hooks)"));
  for (size_t i = 0; i < N_PARAMS; i++)
    Serial.printf("   %-5s = %7.1f  %s\n", PARAMS[i].key, *PARAMS[i].val, PARAMS[i].desc);
}

/** @brief One-line live status (every 5 s and on "status"). */
static void printStatusLine() {
  char t[8], h[8];
  fmtVal(t, sizeof t, sys.tIn);
  fmtVal(h, sizeof h, sys.hum);
  Serial.printf("[%s] In=%sC RH=%s%% Out=%.1fC Light=%.0f%% (raw %u) Knob=%.0f%% Grow=%.0f%% "
                "VentA=%.0f%% VentB=%.0f%% Why=%s Fault=%s\n",
                MODE_NAMES[sys.mode], t, h, cfg.tOutdoor, sys.lightPct, sys.ldrRaw, sys.knobPct,
                sys.growPct, ventPct(sys.curA), ventPct(sys.curB),
                REASON_NAMES[sys.reason], faultName());
}

/** @brief Handle "set <param> <value>". */
static void setParam(const char *key, const char *valStr) {
  if (!key || !valStr) { Serial.println(F("usage: set <param> <value>")); return; }
  char *end;
  float v = strtof(valStr, &end);
  if (end == valStr) { Serial.println(F("value is not a number")); return; }
  for (size_t i = 0; i < N_PARAMS; i++) {
    if (strcmp(key, PARAMS[i].key) == 0) {
      if (v < PARAMS[i].lo || v > PARAMS[i].hi) {
        Serial.printf("out of range (%.0f..%.0f)\n", PARAMS[i].lo, PARAMS[i].hi);
        return;
      }
      *PARAMS[i].val = v;
      Serial.printf("[CFG] %s = %.1f\n", key, v);
      if (cfg.tCrit <= cfg.tVent)        Serial.println(F("[CFG] warning: crit should be above vent"));
      if (cfg.lightOffPct <= cfg.lightOnPct) Serial.println(F("[CFG] warning: loff should be above lon"));
      return;
    }
  }
  Serial.println(F("unknown parameter - type help"));
}

/** @brief Parse and execute one command line. */
static void processCommand(char *line) {
  for (char *p = line; *p; ++p) *p = tolower(*p);
  char *cmd = strtok(line, " ");
  if (!cmd) return;
  char *a1 = strtok(nullptr, " ");
  char *a2 = strtok(nullptr, " ");

  if      (!strcmp(cmd, "help"))   printHelp();
  else if (!strcmp(cmd, "status")) printStatusLine();
  else if (!strcmp(cmd, "manual")) {
    if (sys.mode == MODE_FAULT) Serial.println(F("clear the fault first (ack)"));
    else enterMode(MODE_MANUAL, "serial command");
  }
  else if (!strcmp(cmd, "auto")) {
    if (sys.mode == MODE_FAULT) Serial.println(F("clear the fault first (ack)"));
    else enterMode(MODE_AUTO, "serial command");
  }
  else if (!strcmp(cmd, "ack")) {
    if (sys.mode == MODE_FAULT) tryClearFault("fault acknowledged by serial");
    else Serial.println(F("no active fault"));
  }
  else if (!strcmp(cmd, "set")) setParam(a1, a2);
  else if (!strcmp(cmd, "inject") && a1) {
    if      (!strcmp(a1, "dht")) sys.injectDht = true;
    else if (!strcmp(a1, "ldr")) sys.injectLdr = true;
    else if (!strcmp(a1, "off")) { sys.injectDht = false; sys.injectLdr = false; }
    Serial.printf("[TEST] inject dht=%d ldr=%d\n", sys.injectDht, sys.injectLdr);
  }
  else Serial.println(F("unknown command - type help"));
}

/** @brief Non-blocking serial line reader. */
static void pollSerial() {
  static char buf[64];
  static uint8_t len = 0;
  while (Serial.available()) {
    char c = (char)Serial.read();
    if (c == '\r' || c == '\n') {
      if (len) { buf[len] = '\0'; processCommand(buf); len = 0; }
    } else if (len < sizeof(buf) - 1) {
      buf[len++] = c;
    }
  }
}

