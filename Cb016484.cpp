/** @brief Format a float, or "--.-" if it is not valid yet. */
static void fmtVal(char *buf, size_t n, float v) {
  if (isnan(v)) snprintf(buf, n, "--.-");
  else          snprintf(buf, n, "%.1f", v);
}

/** @brief Draw an inverted title bar. */
static void drawHeader(const char *text) {
  oled.fillRect(0, 0, OLED_WIDTH, 10, SSD1306_WHITE);
  oled.setTextColor(SSD1306_BLACK);
  oled.setCursor(2, 1);
  oled.print(text);
  oled.setTextColor(SSD1306_WHITE);
  oled.setCursor(0, 13);
}

/** @brief Redraw the screen for the current mode (every 500 ms). */
static void drawOled(uint32_t now) {
  if (!gOledOk) return;
  char t[8], h[8], hdr[24];
  fmtVal(t, sizeof t, sys.tIn);
  fmtVal(h, sizeof h, sys.hum);
  oled.clearDisplay();
  oled.setTextSize(1);

  switch (sys.mode) {
    case MODE_AUTO:
      snprintf(hdr, sizeof hdr, "AUTO: %s", REASON_NAMES[sys.reason]);
      drawHeader(hdr);
      oled.printf("In %sC  RH %s%%\n", t, h);
      oled.printf("Out %.1fC  Lt %.0f%%\n", cfg.tOutdoor, sys.lightPct);
      oled.printf("Grow light %.0f%%\n", sys.growPct);
      oled.printf("Vent A %.0f%%  B %.0f%%\n", ventPct(sys.curA), ventPct(sys.curB));
      oled.printf("Set %.1f Crit %.1f\n", cfg.tVent, cfg.tCrit);
      oled.print("BTN: manual override");
      break;

    case MODE_MANUAL: {
      drawHeader("MANUAL OVERRIDE");
      oled.println("Automation SUSPENDED");
      oled.printf("Knob sets vents %.0f%%\n", sys.knobPct);
      oled.printf("Vent A %.0f%%  B %.0f%%\n", ventPct(sys.curA), ventPct(sys.curB));
      oled.printf("In %sC  RH %s%%\n", t, h);
      if (cfg.manualTimeoutS > 0) {
        uint32_t elapsed = (now - sys.manualStartTick) / TICKS_PER_SECOND;
        uint32_t left = (elapsed < cfg.manualTimeoutS) ? (uint32_t)cfg.manualTimeoutS - elapsed : 0;
        oled.printf("Auto resume %02lu:%02lu\n", (unsigned long)(left / 60), (unsigned long)(left % 60));
      } else {
        oled.println("No auto-resume");
      }
      oled.print("BTN: back to AUTO");
      break;
    }

    case MODE_FAULT: {
      bool stillFailed = sys.faultDht || sys.faultLdr;
      drawHeader("!! SENSOR FAULT !!");
      oled.printf("Failed: %s\n", stillFailed ? faultName() : "cleared");
      oled.println("Safe posture active");
      oled.printf("Vent %.0f%%  Grow OFF\n", cfg.safeVentPct);
      if (!sys.faultDht)      oled.printf("In %sC  RH %s%%\n", t, h);
      else if (!sys.faultLdr) oled.printf("Light %.0f%%\n", sys.lightPct);
      else                    oled.println("No valid readings");
      if (stillFailed) { oled.println("Check sensor wiring"); oled.print("Operator required"); }
      else             { oled.println("Sensor OK now");       oled.print("Press BTN to resume"); }
      break;
    }
  }
  oled.display();
}

